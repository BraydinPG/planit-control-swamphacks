"""Next-day briefings (T057, T058; spec.md section 6).

A briefing covers the next workday (07:00–19:00 site-local time). It is built from:

- a fresh deterministic score from Rudra's `score_site()`. Its 0–10 index and level become
  the briefing's `risk_score` and `risk_level`, and each hazard's `points` are the score
  factors it cites (T058C). Gemini never sets or changes any of them.
- the score's factors, active alerts, and confirmed crew reports that say a hazard is
  present.
- the NWS hourly forecast for the workday, reduced to the peak reading of each metric.
- for a confirmed event the model supports, how much longer it is expected to last
  (T058B, `outlooks.py`). It is an advisory estimate; when it is unavailable, that is
  listed in `unknowns`.

Each input becomes an `Evidence` item with an id. Gemini drafts the summary, hazards,
and recommended actions, citing those ids. A draft is rejected, and the deterministic
template is used instead, when Gemini is unavailable, cites an id that was not supplied,
or claims the site is safe or an alert is clear. Inputs that are stale or unavailable
are always listed in `unknowns`, whoever wrote the text.

A briefing is an outlook for the workday ahead: Gemini leads with the forecast, and
mentions current alerts, reports and score factors only as conditions that may carry into
the workday.

Briefings are generated by the 6 PM schedule (`briefing_schedule.py`), stored, and read
back. One briefing per site per workday: its id is `briefing:{site_id}:{date}`.
"""

