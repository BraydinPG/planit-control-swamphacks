logger = logging.getLogger(__name__)

WORKDAY_START = time(7)
WORKDAY_END = time(19)
UNKNOWN_STATES = (DataState.STALE, DataState.UNAVAILABLE)
# A briefing may never tell crews that work is safe or that an alert is over.
FORBIDDEN_PHRASES = (
    "safe to work",
    "safe to resume",
    "work is safe",
    "site is safe",
    "all clear",
    "all-clear",
    "alert has cleared",
    "alert is cleared",
    "no risk",
)

ForecastSource = Callable[[db.Site, datetime], list[Observation]]


class BriefingDraft(BaseModel):
    """What Gemini writes. Validated, then checked against the supplied evidence."""

    summary: str = Field(min_length=1, max_length=700)
    hazards: list["DraftHazard"] = Field(max_length=8)
    recommended_actions: list[RecommendedAction] = Field(max_length=6)
    unknowns: list[str] = Field(default_factory=list, max_length=8)


class DraftHazard(BaseModel):
    """A hazard as drafted: text and the evidence it rests on. Points are added afterwards."""

    model_config = ConfigDict(extra="forbid")

    hazard: str = Field(min_length=1)
    evidence_ids: list[str] = Field(min_length=1)


BriefingDraft.model_rebuild()


@dataclass
class BriefingInputs:
    site_id: str
    site_name: str
    workday: date
    window_start: datetime
    window_end: datetime
    score: HazardScore
    alerts: list[Alert]
    reports: list[CrewReport]
    evidence: list[Evidence] = field(default_factory=list)
    unknowns: list[str] = field(default_factory=list)
    # Evidence id -> index of the score factor it stands for, and that factor's points.
    factor_of: dict[str, int] = field(default_factory=dict)
    points: dict[int, float] = field(default_factory=dict)

    def hazard_points(self, evidence_ids: list[str]) -> float | None:
        """Points the cited score factors add, each counted once; None when none is cited."""
        factors = {self.factor_of[i] for i in evidence_ids if i in self.factor_of}
        if not factors:
            return None
        return round(sum(self.points[f] for f in factors), 1)

    def ids(self, kind: EvidenceKind) -> list[str]:
        return [e.id for e in self.evidence if e.kind == kind]


def briefing_id(site_id: str, workday: date) -> str:
    return f"briefing:{site_id}:{workday.isoformat()}"


def next_workday(now: datetime, tz: ZoneInfo) -> tuple[date, datetime, datetime]:
    """Tomorrow in the site's time zone, and its 07:00–19:00 window in UTC."""
    workday = now.astimezone(tz).date() + timedelta(days=1)
    start = datetime.combine(workday, WORKDAY_START, tzinfo=tz).astimezone(UTC)
    end = datetime.combine(workday, WORKDAY_END, tzinfo=tz).astimezone(UTC)
    return workday, start, end


def generate_site_briefing(
    session: Session,
    site: db.Site,
    tz: ZoneInfo,
    now: datetime,
    gemini: GeminiClient,
    forecasts: ForecastSource,
    outlooks: EventOutlookService | None = None,
) -> Briefing:
    """Generate and store the next-day briefing for one site. Idempotent per workday."""
    workday, _, _ = next_workday(now, tz)
    existing = session.get(db.Briefing, briefing_id(site.id, workday))
    if existing is not None:
        return to_schema(existing)
    inputs = gather_inputs(session, site, tz, now, forecasts, outlooks)
    draft, generated_by = draft_with_gemini(inputs, gemini), GeneratedBy.GEMINI
    if draft is None:
        draft, generated_by = template_draft(inputs), GeneratedBy.FALLBACK
    return store_briefing(session, inputs, draft, generated_by, now)


def store_briefing(
    session: Session,
    inputs: BriefingInputs,
    draft: BriefingDraft,
    generated_by: GeneratedBy,
    now: datetime,
) -> Briefing:
    """Turn a checked draft into the stored briefing: points and gaps come from the inputs."""
    briefing = Briefing(
        id=briefing_id(inputs.site_id, inputs.workday),
        site_id=inputs.site_id,
        forecast_window_start=inputs.window_start,
        forecast_window_end=inputs.window_end,
        summary=draft.summary,
        risk_level=inputs.score.risk_level,
        risk_score=inputs.score.risk_score,
        data_completeness=inputs.score.data_completeness,
        hazards=[
            BriefingHazard(
                hazard=h.hazard,
                points=inputs.hazard_points(h.evidence_ids),
                evidence_ids=h.evidence_ids,
            )
            for h in draft.hazards
        ],
        recommended_actions=draft.recommended_actions,
        evidence=inputs.evidence,
        unknowns=_merge(inputs.unknowns, draft.unknowns),
        generated_by=generated_by,
        created_at=now,
    )
    session.add(_to_row(briefing))
    session.commit()
    logger.info("Generated %s briefing %s", generated_by.value, briefing.id)
    return briefing


def gather_inputs(
    session: Session,
    site: db.Site,
    tz: ZoneInfo,
    now: datetime,
    forecasts: ForecastSource,
    outlooks: EventOutlookService | None = None,
) -> BriefingInputs:
    workday, start, end = next_workday(now, tz)
    score = score_site(session, site.id, now)
    alerts = load_active_alerts(session, site.id)
    reports = [
        r
        for r in load_reports(session, site.id)
        if r.hazard_present and r.review_status == ReviewStatus.CONFIRMED
    ]
    inputs = BriefingInputs(site.id, site.name, workday, start, end, score, alerts, reports)
    inputs.evidence.append(
        Evidence(
            id=f"score:{site.id}",
            kind=EvidenceKind.SCORE_FACTOR,
            label=f"Computed hazard score {score.risk_score:.1f}/10 ({score.risk_level}), "
            f"data completeness {score.data_completeness:.0%}",
            observed_at=score.created_at,
        )
    )
    if score.data_completeness <= 0:
        inputs.unknowns.append(
            "No monitored input (heat, flood, live lightning) is current, so the index is "
            "not evidence of low risk."
        )
    elif score.data_completeness < 1:
        inputs.unknowns.append(
            f"Only {score.data_completeness:.0%} of the monitored inputs (heat, flood, live "
            "lightning) are current; the index may understate conditions."
        )
    for index, factor in enumerate(score.factor_contributions):
        if factor.data_state in UNKNOWN_STATES:
            inputs.unknowns.append(f"{factor.label}: {factor.data_state.value}")
        # A stale reading that still adds points stays a hazard with its points, so the
        # briefing's hazards add up to the stored index. It is also listed as unknown.
        if factor.contribution > 0:
            # Several factors can share a name (one per confirmed report), so ids stay unique.
            evidence_id = f"factor:{site.id}:{factor.factor}"
            if evidence_id in inputs.factor_of:
                evidence_id += f":{factor.evidence_id or index}"
            inputs.evidence.append(
                Evidence(
                    id=evidence_id,
                    kind=EvidenceKind.SCORE_FACTOR,
                    label=f"{factor.label} (+{factor.contribution:g} points, {factor.source})",
                    observed_at=factor.observed_at,
                )
            )
            inputs.factor_of[evidence_id] = index
            if factor.evidence_id:  # citing the alert or report behind it counts the same
                inputs.factor_of.setdefault(factor.evidence_id, index)
            inputs.points[index] = factor.contribution
    for alert in alerts:
        simulated = " (simulated)" if alert.simulated else ""
        inputs.evidence.append(
            Evidence(
                id=alert.id,
                kind=EvidenceKind.ALERT,
                label=f"Active {alert.rule.replace('_', ' ')} alert{simulated}",
                observed_at=alert.latest_event_at,
            )
        )
    for report in reports:
        severity = f", {report.confirmed_severity}" if report.confirmed_severity else ""
        category = (report.confirmed_category or report.category).replace("_", " ")
        inputs.evidence.append(
            Evidence(
                id=report.id,
                kind=EvidenceKind.REPORT,
                label=f"Confirmed crew report: {category}{severity}",
                observed_at=report.created_at,
            )
        )
    outlook = site_outlook(session, site, now, outlooks) if outlooks else None
    if outlook is not None:
        if (evidence := outlook_evidence(outlook)) is not None:
            inputs.evidence.append(evidence)
        else:
            inputs.unknowns.append(missing_estimate(outlook))
    peaks = _forecast_peaks(forecasts(site, now), start, end, tz)
    inputs.evidence.extend(peaks)
    if not peaks:
        inputs.unknowns.append("NWS forecast for the workday is unavailable.")
    return inputs


def draft_with_gemini(inputs: BriefingInputs, gemini: GeminiClient) -> BriefingDraft | None:
    """Gemini's draft, or None when it is unavailable or breaks a rule."""
    result = gemini.generate_structured(_prompt(inputs), BriefingDraft)
    if not result.ok:
        logger.info("Briefing for %s uses the template: %s", inputs.site_id, result.unavailable)
        return None
    draft = result.value
    supplied = {e.id for e in inputs.evidence}
    cited = {i for item in [*draft.hazards, *draft.recommended_actions] for i in item.evidence_ids}
    if not cited <= supplied:
        logger.warning("Gemini briefing cited unknown evidence; using the template")
        return None
    text = " ".join(
        [draft.summary, *(h.hazard for h in draft.hazards)]
        + [a.action for a in draft.recommended_actions]
        + draft.unknowns
    ).lower()
    if any(phrase in text for phrase in FORBIDDEN_PHRASES):
        logger.warning("Gemini briefing claimed safety or an all-clear; using the template")
        return None
    return draft


def template_draft(inputs: BriefingInputs) -> BriefingDraft:
    """Deterministic briefing from the same inputs (T058). No generated text."""
    # One hazard per score factor; an alert or report only when no factor covers it.
    supplied = {e.id for e in inputs.evidence}
    behind = {
        source: factor_id
        for factor_id, index in inputs.factor_of.items()
        if factor_id.startswith("factor:")
        for source, i in inputs.factor_of.items()
        if i == index and not source.startswith("factor:") and source in supplied
    }
    hazards = []
    for e in inputs.evidence:
        if e.kind == EvidenceKind.SCORE_FACTOR and e.id in inputs.factor_of:
            cited = [e.id, *(s for s, f in behind.items() if f == e.id)]
            hazards.append(DraftHazard(hazard=e.label, evidence_ids=cited))
        elif e.kind in (EvidenceKind.ALERT, EvidenceKind.REPORT) and e.id not in behind:
            hazards.append(DraftHazard(hazard=e.label, evidence_ids=[e.id]))
        elif e.kind == EvidenceKind.MODEL_OUTPUT:
            hazards.append(DraftHazard(hazard=e.label, evidence_ids=[e.id]))
    # The forecast comes first: a briefing is an outlook for the workday ahead.
    actions: list[RecommendedAction] = []
    if forecast_ids := inputs.ids(EvidenceKind.OBSERVATION):
        actions.append(
            RecommendedAction(
                action="Plan the workday around the forecast peaks listed in this briefing.",
                evidence_ids=forecast_ids,
            )
        )
    if alert_ids := inputs.ids(EvidenceKind.ALERT):
        actions.append(
            RecommendedAction(
                action="Check the active alerts again before work starts. Stop-work alerts "
                "stay in force until the system clears them.",
                evidence_ids=alert_ids,
            )
        )
    if report_ids := inputs.ids(EvidenceKind.REPORT):
        actions.append(
            RecommendedAction(
                action="Review the confirmed crew reports before work starts.",
                evidence_ids=report_ids,
            )
        )
    score = inputs.score
    summary = (
        f"Template briefing for {inputs.site_name}, {inputs.workday:%A %B} "
        f"{inputs.workday.day}. Computed hazard score {score.risk_score:.1f}/10 "
        f"({score.risk_level}) with {score.data_completeness:.0%} of its inputs current. "
        "Gemini text was not used, so this briefing lists the inputs without generated "
        "wording."
    )
    return BriefingDraft(summary=summary, hazards=hazards, recommended_actions=actions)


def to_schema(row: db.Briefing) -> Briefing:
    return Briefing(
        id=row.id,
        site_id=row.site_id,
        organization_id=row.organization_id,
        forecast_window_start=_aware(row.forecast_window_start),
        forecast_window_end=_aware(row.forecast_window_end),
        summary=row.summary,
        risk_level=row.risk_level,
        risk_score=row.risk_score,
        data_completeness=row.data_completeness,
        # Hazards stored before T058C carry a level word and no points.
        hazards=[
            BriefingHazard(
                hazard=h["hazard"], points=h.get("points"), evidence_ids=h["evidence_ids"]
            )
            for h in row.hazards
        ],
        recommended_actions=row.recommended_actions,
        evidence=row.evidence,
        unknowns=row.unknowns,
        generated_by=row.generated_by,
        created_at=_aware(row.created_at),
    )


def _to_row(briefing: Briefing) -> db.Briefing:
    data = briefing.model_dump(mode="json")
    return db.Briefing(
        id=briefing.id,
        site_id=briefing.site_id,
        organization_id=briefing.organization_id,
        forecast_window_start=briefing.forecast_window_start,
        forecast_window_end=briefing.forecast_window_end,
        summary=briefing.summary,
        risk_level=briefing.risk_level,
        risk_score=briefing.risk_score,
        data_completeness=briefing.data_completeness,
        hazards=data["hazards"],
        recommended_actions=data["recommended_actions"],
        evidence=data["evidence"],
        unknowns=briefing.unknowns,
        generated_by=briefing.generated_by,
        created_at=briefing.created_at,
    )


def _forecast_peaks(
    observations: list[Observation], start: datetime, end: datetime, tz: ZoneInfo
) -> list[Evidence]:
    """The highest forecast reading of each metric inside the workday window."""
    peaks: dict[str, Observation] = {}
    for o in observations:
        if o.hazard_type != HazardType.FORECAST or o.data_state != DataState.FORECAST:
            continue
        if o.id is None or o.valid_at is None or not isinstance(o.value, int | float):
            continue
        if not start <= o.valid_at < end:
            continue
        label = o.label or "Forecast value"
        if label not in peaks or o.value > peaks[label].value:
            peaks[label] = o
    return [
        Evidence(
            id=o.id,
            kind=EvidenceKind.OBSERVATION,
            label=f"Forecast {label.lower()} up to {o.value:g}{_unit(o.unit)} at "
            f"{o.valid_at.astimezone(tz):%H:%M} local ({o.source})",
            observed_at=o.valid_at,
        )
        for label, o in sorted(peaks.items())
    ]


def _prompt(inputs: BriefingInputs) -> str:
    evidence = [
        {"id": e.id, "kind": e.kind.value, "label": e.label, "time": _iso(e.observed_at)}
        for e in inputs.evidence
    ]
    return (
        "You write the next-day safety briefing for a utility field crew. Crews read it the "
        "evening before, so it is an outlook: what to watch for during tomorrow's workday, "
        "not what to do right now.\n"
        f"Site: {inputs.site_name}. Workday: {inputs.workday.isoformat()}, 07:00-19:00 local.\n"
        f"The site's computed hazard score is {inputs.score.risk_score:.1f}/10 "
        f"({inputs.score.risk_level}), with {inputs.score.data_completeness:.0%} of its inputs "
        "current. The briefing shows this index and each hazard's points itself, so do not "
        "write any score, points, or risk level, and never present missing data as low "
        "risk.\n\n"
        "Rules:\n"
        "- Use only the evidence below. Every hazard and recommended action must cite one "
        "or more evidence ids from this list in evidence_ids. A hazard that a score factor "
        "describes (ids starting with factor:) must cite that factor.\n"
        "- Never say or imply that work is safe, that the site is safe, or that an alert "
        "is clear or over. Alerts are cleared only by the system.\n"
        "- Lead with the workday forecast (evidence labels starting with \"Forecast\"): what "
        "is expected, when it peaks, and what the crew should plan around.\n"
        "- Active alerts, crew reports and score factors describe conditions now. Mention "
        "them only as conditions that may carry into the workday and must be checked again "
        "at the start of the shift. Do not write instructions for right now.\n"
        "- Keep the summary to 2-3 short sentences in plain language, written about the "
        "workday ahead.\n"
        "- Recommended actions are preparation for the workday (scheduling, equipment, "
        "checks at the start of the shift), at most 4.\n"
        "- If the evidence includes an expected-duration estimate (kind model_output), say in "
        "plain words how much longer the event is expected to last, call it an estimate, "
        "and cite it. Never turn it into a time when work can resume.\n"
        "- List anything important that the evidence does not cover in unknowns.\n\n"
        f"Evidence:\n{json.dumps(evidence, indent=1)}\n\n"
        "Known gaps (already listed in the briefing; do not repeat or reword them in "
        f"unknowns):\n{json.dumps(inputs.unknowns)}\n"
    )


def _merge(first: list[str], second: list[str]) -> list[str]:
    return list(dict.fromkeys([*first, *second]))


def _unit(unit: str | None) -> str:
    if not unit:
        return ""
    return unit if unit in ("°F", "%") else f" {unit}"


def _iso(value: datetime | None) -> str | None:
    return value.isoformat() if value else None


def _aware(value: datetime) -> datetime:
    return value if value.tzinfo else value.replace(tzinfo=UTC)
