"""Site species context: read-only wildlife field awareness for a team's site.

Two independent dimensions per species, either of which may be unknown:

- `protection`: legal status from the USFWS IPaC Location API (federal ESA listing).
- `encounter`: curated worker-encounter guidance from a cited public source.

Protected never implies dangerous, and dangerous never implies protected. IPaC lists
species whose *range* intersects the area around the site. That is regional context,
never a sighting. Crew wildlife reports stay in their own list.

Nothing here feeds the hazard score, alerts, report confirmation, or work clearance.
"""

from datetime import date, datetime
from enum import StrEnum
from typing import Any, Literal

from pydantic import Field

from app.schemas.common import DataState, GeneratedBy, Schema

SPECIES_CAVEAT = (
    "Regional context, not a sighting. These species are listed because their known range "
    "or critical habitat overlaps the area around this site. Verify locally and follow "
    "your site's wildlife procedures. This is not legal advice and does not clear work."
)


class MatchBasis(StrEnum):
    """Why a species appears for this site."""

    REGIONAL_RANGE = "regional_range"  # IPaC range intersects the site footprint
    POSSIBLE_REGIONAL_CONTEXT = "possible_regional_context"  # IPaC range has office conditions
    CONFIRMED_REPORT = "confirmed_report"  # a human-reviewed crew report
    UNKNOWN = "unknown"


class ProtectionStatus(Schema):
    """Federal listing status exactly as IPaC supplied it."""

    jurisdiction: str = Field(description='e.g. "U.S. federal (Endangered Species Act)".')
    status: str | None = Field(description="IPaC listingStatusName; null when not supplied.")
    status_code: str | None = None
    description: str | None = None
    critical_habitat_here: bool | None = Field(
        default=None,
        description="IPaC crithabInFootprint. Null when IPaC did not say.",
    )
    source: str
    source_url: str | None = None
    as_of: datetime = Field(description="When FORESITE retrieved this record.")
    evidence_id: str


class EncounterGuidance(Schema):
    """Curated, cited encounter guidance. Never generated by Gemini."""

    hazard: str | None = Field(description="Why an encounter may matter; null when not sourced.")
    actions: list[str]
    contact: str | None = None
    source: str
    source_url: str
    review_status: str = Field(description='"pending_review" until a safety lead signs off.')
    reviewed_by: str | None = None
    evidence_id: str


class SpeciesEntry(Schema):
    id: str = Field(description='Stable id, e.g. "ipac:Population$Sid[8396]".')
    common_name: str | None
    scientific_name: str | None
    group: str | None = Field(description='IPaC groupName, e.g. "Reptiles".')
    match_basis: MatchBasis
    match_note: str
    protection: ProtectionStatus | None
    encounter: EncounterGuidance | None
    summary: str = Field(description="Crew-readable text built only from the fields above.")
    summary_by: GeneratedBy
    evidence_ids: list[str]


class CriticalHabitatArea(Schema):
    """A USFWS critical habitat feature near the site, as the map service supplied it."""

    id: str
    common_name: str | None
    scientific_name: str | None
    status: str | None = Field(description='"Final" or "Proposed".')
    listing_status: str | None
    federal_register: str | None
    published: date | None
    source: str
    source_url: str
    geometry: dict[str, Any] | None = Field(
        description="GeoJSON clipped to the map window, or null when no boundary is drawn."
    )
    geometry_note: str | None = None


class FieldOfficeContact(Schema):
    name: str
    phone: str | None = None
    email: str | None = None


class WildlifeReportRef(Schema):
    """A crew wildlife report at this site. Kept apart from regional species context."""

    report_id: str
    reported_at: datetime
    hazard_present: bool
    confirmation: Literal["confirmed", "pending", "rejected"]
    match_basis: MatchBasis
    note: str | None = None


class SiteSpeciesContext(Schema):
    site_id: str
    source: str
    source_url: str
    api_version: str | None
    data_state: DataState
    simulated: bool = False
    fetched_at: datetime | None
    footprint_description: str
    location_description: str | None
    field_office: FieldOfficeContact | None
    species: list[SpeciesEntry]
    critical_habitat: list[CriticalHabitatArea]
    critical_habitat_state: DataState
    critical_habitat_source: str
    wildlife_reports: list[WildlifeReportRef]
    generated_by: GeneratedBy
    unknowns: list[str]
    caveat: str = SPECIES_CAVEAT
